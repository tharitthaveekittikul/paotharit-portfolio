import { readFileSync, readdirSync, writeFileSync } from 'fs'
import { join } from 'path'
import matter from 'gray-matter'

const root = process.cwd()
const messages = JSON.parse(readFileSync(join(root, 'src/i18n/messages/en.json'), 'utf8'))
const projectsDir = join(root, 'content/en/projects')
const out = join(root, 'src/lib/ask/knowledge-brief.md')

async function summarize(title: string, frontmatter: Record<string, unknown>, body: string) {
  const prompt = [
    'Summarize this project for a recruiter using only facts in the text. Output exactly this shape and nothing else:',
    'One plain sentence saying what the project is.',
    '- Role: ...',
    '- Stack: ...',
    '- What Tharit did: ...',
    '- Outcome and metrics: ...',
    '- Limits: ... (scope, status, or anything not finished)',
    'Write "not stated" when the text does not say. No praise words, no marketing language, under 140 words.',
    '',
    `Title: ${title}`,
    `Frontmatter: ${JSON.stringify(frontmatter)}`,
    `Body:\n${body.slice(0, 12000)}`,
  ].join('\n')
  const response = await fetch('https://api.z.ai/api/paas/v4/chat/completions', {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: `Bearer ${process.env.ZAI_API_KEY}` },
    body: JSON.stringify({
      model: 'glm-5.3-flash',
      messages: [{ role: 'user', content: prompt }],
      max_tokens: 500,
      temperature: 0.2,
      reasoning_effort: 'low',
    }),
  })
  if (!response.ok) throw new Error(`GLM ${response.status}: ${await response.text()}`)
  const data = await response.json()
  return (data.choices[0].message.content as string).trim()
}

function profile() {
  const { about, workExperience: w, education: e } = messages
  return [
    '# Profile',
    '<!-- DRAFT: generated by scripts/draft-knowledge-brief.ts. Review every line before shipping. -->',
    'Name: Tharit Thaveekittikul. Software engineer based in Bangkok, Thailand (GMT+7). Open to new opportunities.',
    `Tharit's own words (first person in the source): ${about.bio}`,
    `Tharit's own words on what he wants (first person in the source): ${about.closing}`,
    `Work: ${w.scb.company}, ${w.scb.role}, ${w.scb.years}. ${w.scb.bullet1}. ${w.scb.bullet2}.`,
    `Work: ${w.pompkins.company}, ${w.pompkins.role}, ${w.pompkins.years}. ${w.pompkins.bullet1}. ${w.pompkins.bullet2}.`,
    `Education: ${e.university.name}, ${e.university.degree}, ${e.university.years}, ${e.university.gpa}, ${e.university.honors}. ${e.university.ta}. ${e.university.volunteer}.`,
    `Languages: Thai ${about.languages.thai.level}; English ${about.languages.english.level}; Japanese ${about.languages.japanese.level}; Mandarin ${about.languages.mandarin.level}.`,
    `Outside work: ${about.outside.travel} ${String(about.outside.finance).replace(/<\/?[a-z]+>/g, '')} ${about.outside.learning} ${about.outside.games}`,
  ].join('\n')
}

async function main() {
  const files = readdirSync(projectsDir).filter((f) => f.endsWith('.mdx')).sort()
  const sections: string[] = []
  for (const file of files) {
    const slug = file.replace('.mdx', '')
    const { data, content } = matter(readFileSync(join(projectsDir, file), 'utf8'))
    if (data.status && data.status !== 'published') continue
    console.log(`drafting ${slug}`)
    const summary = await summarize(String(data.title), data, content)
    sections.push(`## ${slug} | ${data.title}\n${summary}`)
  }
  writeFileSync(out, `${profile()}\n\n# Projects\n\n${sections.join('\n\n')}\n`)
  console.log(`wrote ${out}`)
}

main()
